def art_to_bytes(rows):
    """7 strings of 5 chars -> 5 bytes, one per column, bit 0 = top pixel."""
    cols = []
    for x in range(5):
        byte = 0
        for y in range(7):
            if rows[y][x] == '#':
                byte |= (1 << y)
        cols.append(byte)
    return cols


def bytes_to_art(cols):
    """Inverse of art_to_bytes, used to prove the conversion round-trips."""
    return ["".join('#' if cols[x] & (1 << y) else '_' for x in range(5))
            for y in range(7)]


def check():
    problems = []
    for ch in range(32, 127):
        c = chr(ch)
        if c not in ART:
            problems.append("missing glyph for %r" % c)
            continue
        rows = ART[c]
        if len(rows) != 7:
            problems.append("%r has %d rows, expected 7" % (c, len(rows)))
        for r in rows:
            if len(r) != 5:
                problems.append("%r has a row of %d columns, expected 5" % (c, len(r)))
            if set(r) - set("#_"):
                problems.append("%r uses characters other than # and _" % c)
        if bytes_to_art(art_to_bytes(rows)) != rows:
            problems.append("%r does not survive the round trip" % c)
    return problems


def render(text):
    """Draw a string the way the OLED will, for visual checking."""
    lines = [""] * 8
    for c in text:
        cols = art_to_bytes(ART[c]) + [0]
        for y in range(8):
            lines[y] += "".join('#' if col & (1 << y) else ' ' for col in cols)
    return "\n".join(lines)


def emit(path):
    out = []
    out.append("/******************************************************************************")
    out.append(" * @file           : oled_font.h")
    out.append(" * @brief          : 5x7 character shapes in a 6x8 cell for the OLED")
    out.append(" *")
    out.append(" * What:  one entry per printable ASCII character, 32 (space) to 126 (~).")
    out.append(" *        Each entry is 5 bytes; oled.c adds a 6th blank byte as the gap")
    out.append(" *        between characters, giving 21 characters across a 128 pixel row.")
    out.append(" * Where: sensor -> EWMA -> features -> state machine -> [OLED] (see oled.c).")
    out.append(" *")
    out.append(" * One byte is a column of 8 pixels with bit 0 at the top, which is how the")
    out.append(" * SSD1306 stores its display RAM. Bit 7 is always 0, leaving a one pixel")
    out.append(" * gap under each text row.")
    out.append(" *")
    out.append(" * GENERATED FILE - do not hand edit. The pixel art it comes from, and the")
    out.append(" * script that converts it, live in tools/make_font.py.")
    out.append(" ******************************************************************************/")
    out.append("#ifndef OLED_FONT_H")
    out.append("#define OLED_FONT_H")
    out.append("")
    out.append("#include <stdint.h>")
    out.append("")
    out.append("#define OLED_FONT_FIRST   32   /* ASCII code of the first entry, space */")
    out.append("#define OLED_FONT_LAST   126   /* ASCII code of the last entry, tilde */")
    out.append("#define OLED_FONT_WIDTH    5   /* pixel columns per character, plus 1 gap */")
    out.append("")
    out.append("static const uint8_t OLED_FONT[OLED_FONT_LAST - OLED_FONT_FIRST + 1][OLED_FONT_WIDTH] =")
    out.append("{")
    for ch in range(32, 127):
        c = chr(ch)
        cols = art_to_bytes(ART[c])
        shown = "space" if c == ' ' else ("backslash" if c == '\\' else c)
        out.append("    { %s },   /* %-9s */" % (
            ", ".join("0x%02X" % b for b in cols), shown))
    out.append("};")
    out.append("")
    out.append("#endif /* OLED_FONT_H */")
    with open(path, "w", newline="\r\n") as f:
        f.write("\n".join(out) + "\n")


